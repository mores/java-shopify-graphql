package com.shopify.storefront.types;

/**
 * List of different delivery method types.
 */
public enum DeliveryMethodType {
  /**
   * Shipping.
   */
  SHIPPING,

  /**
   * Local Pickup.
   */
  PICK_UP,

  /**
   * Retail.
   */
  RETAIL,

  /**
   * Local Delivery.
   */
  LOCAL,

  /**
   * Shipping to a Pickup Point.
   */
  PICKUP_POINT,

  /**
   * None.
   */
  NONE
}
