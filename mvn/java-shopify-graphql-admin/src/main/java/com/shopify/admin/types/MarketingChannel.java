package com.shopify.admin.types;

/**
 * The medium through which the marketing activity and event reached consumers. This is used for reporting aggregation.
 */
public enum MarketingChannel {
  /**
   * Paid search.
   */
  SEARCH,

  /**
   * Displayed ads.
   */
  DISPLAY,

  /**
   * Social media.
   */
  SOCIAL,

  /**
   * Email.
   */
  EMAIL,

  /**
   * Referral links.
   */
  REFERRAL
}
