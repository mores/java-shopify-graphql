package com.shopify.admin.types;

/**
 * The set of valid sort keys for the MarketingActivity query.
 */
public enum MarketingActivitySortKeys {
  /**
   * Sort by the `created_at` value.
   */
  CREATED_AT,

  /**
   * Sort by the `id` value.
   */
  ID,

  /**
   * Sort by the `title` value.
   */
  TITLE
}
