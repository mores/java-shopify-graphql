package com.shopify.admin.types;

/**
 * Available shop policy types.
 */
public enum ShopPolicyType {
  /**
   * The refund policy.
   */
  REFUND_POLICY,

  /**
   * The shipping policy.
   */
  SHIPPING_POLICY,

  /**
   * The privacy policy.
   */
  PRIVACY_POLICY,

  /**
   * The terms of service.
   */
  TERMS_OF_SERVICE,

  /**
   * The terms of sale.
   */
  TERMS_OF_SALE,

  /**
   * The legal notice.
   */
  LEGAL_NOTICE,

  /**
   * The cancellation policy.
   */
  SUBSCRIPTION_POLICY,

  /**
   * The contact information.
   */
  CONTACT_INFORMATION
}
