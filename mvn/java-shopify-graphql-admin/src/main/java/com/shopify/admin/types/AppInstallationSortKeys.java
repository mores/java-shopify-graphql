package com.shopify.admin.types;

/**
 * The set of valid sort keys for the AppInstallation query.
 */
public enum AppInstallationSortKeys {
  /**
   * Sort by the `app_title` value.
   */
  APP_TITLE,

  /**
   * Sort by the `id` value.
   */
  ID,

  /**
   * Sort by the `installed_at` value.
   */
  INSTALLED_AT
}
