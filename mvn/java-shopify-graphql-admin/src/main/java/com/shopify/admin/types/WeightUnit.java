package com.shopify.admin.types;

/**
 * Units of measurement for weight.
 */
public enum WeightUnit {
  /**
   * 1 kilogram equals 1000 grams.
   */
  KILOGRAMS,

  /**
   * Metric system unit of mass.
   */
  GRAMS,

  /**
   * 1 pound equals 16 ounces.
   */
  POUNDS,

  /**
   * Imperial system unit of mass.
   */
  OUNCES
}
