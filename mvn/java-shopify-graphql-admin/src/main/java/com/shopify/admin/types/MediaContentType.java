package com.shopify.admin.types;

/**
 * The possible content types for a media object.
 */
public enum MediaContentType {
  /**
   * A Shopify-hosted video.
   */
  VIDEO,

  /**
   * An externally hosted video.
   */
  EXTERNAL_VIDEO,

  /**
   * A 3d model.
   */
  MODEL_3D,

  /**
   * A Shopify-hosted image.
   */
  IMAGE
}
